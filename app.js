const inlineForm = document.getElementById('inline-callback-form');
const modalLeadForm = document.getElementById('modal-lead-form');

function handleFormSubmit(e, formType) {
    e.preventDefault();
    
    let name = '';
    let phone = '';
    let car = '';
    
    if (formType === 'inline') {
        name = document.getElementById('form-name').value;
        phone = document.getElementById('form-phone').value;
        car = document.getElementById('form-car').value;
    } else {
        name = document.getElementById('modal-name').value;
        phone = document.getElementById('modal-phone').value;
        car = document.getElementById('modal-lead-car').value;
    }

    // Basic validation of phone number length
    if (phone.length < 19) {
        alert(currentLang === 'ru' ? 'Пожалуйста, введите полный номер телефона.' : 'Iltimos, telefon raqamini to\'liq kiriting.');
        return;
    }

    // Package the Lead
    const lead = {
        name,
        phone,
        car,
        date: new Date().toISOString(),
        type: formType,
        calculatorData: formType === 'modal' ? {
            price: document.getElementById('modal-lead-price').value,
            monthlyPayment: document.getElementById('modal-lead-payment').value,
            term: document.getElementById('modal-lead-term').value
        } : null
    };

    // Store in localStorage (Simulated Database)
    let leads = JSON.parse(localStorage.getItem('jac_motors_leads') || '[]');
    leads.push(lead);
    localStorage.setItem('jac_motors_leads', JSON.stringify(leads));

    // Show Success Modal
    if (formType === 'modal') {
        leadModal.classList.remove('open');
    }
    
    successModal.classList.add('open');
    document.body.style.overflow = 'hidden';

    // Clear Form inputs
    e.target.reset();
}

if (inlineForm) inlineForm.addEventListener('submit', (e) => handleFormSubmit(e, 'inline'));
if (modalLeadForm) modalLeadForm.addEventListener('submit', (e) => handleFormSubmit(e, 'modal'));

