function getInterestRate(carModel, downpayment, term) {
    if (carModel === 'JAC JS8 PRO') {
        const dpVal = Math.round(downpayment / 10) * 10;
        if (js8Rates[dpVal] && js8Rates[dpVal][term] !== undefined) {
            return js8Rates[dpVal][term];
        }
        return 18.92;
    }
    if (carModel === 'JAC M3 Passenger' || carModel === 'JAC M3 Cargo' || carModel === 'JAC Sunray') {
        const dpVal = Math.round(downpayment / 10) * 10;
        if (minivanRates[dpVal] && minivanRates[dpVal][term] !== undefined) {
            return minivanRates[dpVal][term];
        }
        return 16.50;
    }
    return 25.00; // default for other models (T9, T8, M4, RF8, Sunray Van)
}

function setTermRadioOptions(terms) {
    const container = document.getElementById('term-radio-group-container');
    if (!container) return;
    
    let checkedValue = null;
    const radios = container.querySelectorAll('.term-radio');
    for (const r of radios) {
        if (r.checked) {
            checkedValue = parseInt(r.value);
            break;
        }
    }
    
    if (checkedValue === null || !terms.includes(checkedValue)) {
        checkedValue = terms.includes(36) ? 36 : (terms.includes(24) ? 24 : terms[0]);
    }
    
    container.innerHTML = '';
    
    terms.forEach(t => {
        const label = document.createElement('label');
        label.className = 'term-btn-label';
        
        const input = document.createElement('input');
        input.type = 'radio';
        input.name = 'calc-term';
        input.value = t.toString();
        input.className = 'term-radio';
        if (t === checkedValue) {
            input.checked = true;
        }
        
        const span = document.createElement('span');
        span.setAttribute('data-i18n', `m-${t}`);
        
        const monthsText = currentLang === 'ru' ? 'мес.' : 'oy';
        span.textContent = `${t} ${monthsText}`;
        
        label.appendChild(input);
        label.appendChild(span);
        container.appendChild(label);
        
        input.addEventListener('change', calculateCredit);
    });
}

