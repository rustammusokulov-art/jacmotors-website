function setLanguage(lang) {
    if (!translations[lang]) return;
    currentLang = lang;
    
    // Update active class on all buttons
    document.querySelectorAll('.lang-btn').forEach(btn => {
        if (btn.getAttribute('data-lang') === lang) {
            btn.classList.add('active');
        } else {
            btn.classList.remove('active');
        }
    });

    // Translate marked elements
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (translations[lang][key]) {
            // Check if element is an input or has placeholders
            if (element.tagName === 'INPUT' && element.getAttribute('placeholder')) {
                // If we have custom placeholder translation we could map it, but for simplicity:
                if (key.endsWith('-placeholder')) {
                    element.setAttribute('placeholder', translations[lang][key]);
                }
            } else {
                element.innerHTML = translations[lang][key];
            }
        }
    });

    // Re-translate placeholders manually if needed
    const placeholders = {
        ru: {
            "form-name": "Например, Александр",
            "form-phone": "+998 (__) ___-__-__",
            "modal-name": "Например, Александр",
            "modal-phone": "+998 (__) ___-__-__",
            "calc-price-input": "299 000 000"
        },
        uz: {
            "form-name": "Masalan, Sardor",
            "form-phone": "+998 (__) ___-__-__",
            "modal-name": "Masalan, Sardor",
            "modal-phone": "+998 (__) ___-__-__",
            "calc-price-input": "299 000 000"
        }
    };

    document.querySelectorAll('#form-name, #modal-name').forEach(el => {
        el.setAttribute('placeholder', placeholders[lang][el.id]);
    });

    // Save language setting
    localStorage.setItem('jac_site_lang', lang);
    
    // Update current calculator outputs with localized labels
    updateCalculatorOptions();
    calculateCredit();
}

