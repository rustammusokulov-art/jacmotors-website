function calculateCredit() {
    const price = parseUZS(priceInput.value);
    const downpaymentPercent = parseInt(downpaymentRange.value);
    
    const downpaymentSum = Math.round(price * (downpaymentPercent / 100));
    
    // Get Selected Term
    let termMonths = 12;
    const container = document.getElementById('term-radio-group-container');
    if (container) {
        const checkedRadio = container.querySelector('.term-radio:checked');
        if (checkedRadio) {
            termMonths = parseInt(checkedRadio.value);
        }
    }

    // Get dynamic rate
    const selectedOption = carSelect.options[carSelect.selectedIndex];
    const carName = selectedOption ? selectedOption.getAttribute('data-name') : 'custom';
    const annualRate = getInterestRate(carName, downpaymentPercent, termMonths);
    
    const loanAmount = price - downpaymentSum;
    let monthlyPayment = 0;
    let totalPayout = 0;
    let totalOverpayment = 0;

    if (loanAmount > 0) {
        if (annualRate > 0) {
            const monthlyRate = (annualRate / 12) / 100;
            monthlyPayment = Math.round(loanAmount * (monthlyRate * Math.pow(1 + monthlyRate, termMonths)) / (Math.pow(1 + monthlyRate, termMonths) - 1));
        } else {
            monthlyPayment = Math.round(loanAmount / termMonths); // 0% rate fallback
        }
        totalPayout = monthlyPayment * termMonths;
        totalOverpayment = totalPayout - loanAmount;
    }

    // UI Updates
    downpaymentPercentDisplay.textContent = downpaymentPercent + '%';
    downpaymentSumDisplay.textContent = formatUZS(downpaymentSum);
    
    // Localized years/months text
    let yearPart = '';
    if (termMonths === 12) yearPart = currentLang === 'ru' ? ' (1 год)' : ' (1 yil)';
    else if (termMonths === 24) yearPart = currentLang === 'ru' ? ' (2 года)' : ' (2 yil)';
    else if (termMonths === 36) yearPart = currentLang === 'ru' ? ' (3 года)' : ' (3 yil)';
    else if (termMonths === 48) yearPart = currentLang === 'ru' ? ' (4 года)' : ' (4 yil)';
    else if (termMonths === 60) yearPart = currentLang === 'ru' ? ' (5 лет)' : ' (5 yil)';
    
    const termLabelText = currentLang === 'ru' ? 'мес.' : 'oy';
    termDisplay.textContent = `${termMonths} ${termLabelText}${yearPart}`;
    
    rateDisplay.textContent = annualRate.toFixed(2) + '%';

    // Set Outputs
    monthlyPaymentVal.textContent = formatUZS(monthlyPayment);
    loanAmountVal.textContent = formatUZS(loanAmount);
    loanDownpaymentVal.textContent = formatUZS(downpaymentSum);
    loanOverpaymentVal.textContent = formatUZS(totalOverpayment);
    loanTotalVal.textContent = formatUZS(totalPayout);

    // Update lead generation form hidden fields
    document.getElementById('modal-lead-car').value = carName;
    document.getElementById('modal-lead-price').value = price;
    document.getElementById('modal-lead-payment').value = monthlyPayment;
    document.getElementById('modal-lead-term').value = termMonths;
}

