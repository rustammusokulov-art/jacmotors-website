// PHONE MASKING LOGIC (+998 (XX) XXX-XX-XX)
// ==========================================================================
const phoneInputs = document.querySelectorAll('#form-phone, #modal-phone');

phoneInputs.forEach(input => {
    // Initial value prefix
    input.addEventListener('focus', () => {
        if (!input.value) {
            input.value = '+998 ';
        }
    });

    input.addEventListener('keydown', (e) => {
        // Prevent deleting prefix +998
        if (input.value.length <= 5 && (e.key === 'Backspace' || e.key === 'Delete')) {
            e.preventDefault();
        }
    });

    input.addEventListener('input', (e) => {
        let value = input.value;
        
        // Remove all non-digits except first +
        let numbers = value.replace(/[^\d]/g, '');
        
        // Ensure starting with 998
        if (!numbers.startsWith('998')) {
            numbers = '998' + numbers;
        }

        let formatted = '+998 ';
        
        if (numbers.length > 3) {
            formatted += '(' + numbers.substring(3, 5);
        }
        if (numbers.length > 5) {
            formatted += ') ' + numbers.substring(5, 8);
        }
        if (numbers.length > 8) {
            formatted += '-' + numbers.substring(8, 10);
        }
        if (numbers.length > 10) {
            formatted += '-' + numbers.substring(10, 12);
        }

        input.value = formatted.substring(0, 19);
    });
});

